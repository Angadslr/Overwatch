import { mkdir, readFile, writeFile } from 'node:fs/promises';

const schema = JSON.parse(await readFile(new URL('../schemas/event-v1.schema.json', import.meta.url), 'utf8'));
const output = new URL('../src/core/contracts.ts', import.meta.url);

// Generate shape types only. JSON Schema remains authoritative for ranges and cross-field rules.
function typeOf(node, depth = 0) {
  if (node.$ref) return node.$ref.replace('#/definitions/', '');
  if (Object.hasOwn(node, 'const')) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(' | ');
  switch (node.type) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return `Array<${typeOf(node.items, depth)}>`;
    case 'object': {
      const required = new Set(node.required ?? []);
      const indent = '  '.repeat(depth + 1);
      const fields = Object.entries(node.properties).map(([key, value]) =>
        `${indent}${key}${required.has(key) ? '' : '?'}: ${typeOf(value, depth + 1)};`);
      return `{\n${fields.join('\n')}\n${'  '.repeat(depth)}}`;
    }
    default: throw new Error('Unsupported schema shape; update the generator explicitly.');
  }
}

const declarations = [...Object.entries(schema.definitions), [schema.title, schema]]
  .map(([name, node]) => `export type ${name} = ${typeOf(node)};`);
const generated = [
  '// Generated by npm run generate:contracts from schemas/event-v1.schema.json. Do not hand edit.',
  '// Runtime validation enforces bounds, identity requirements and evidence combinations.',
  `export const EVENT_SCHEMA_VERSION = ${schema.properties.schemaVersion.const} as const;`,
  `export const MAX_EVENT_BYTES = ${schema['x-maxUtf8Bytes']} as const;`,
  ...declarations,
  "export type SpoolEventV1 = Omit<EventV1, 'ingestSequence'> & { ingestSequence?: never };",
  'export type JournalEventV1 = EventV1 & { ingestSequence: number };',
  '',
].join('\n\n');

// Go shape types share the same source. Pointers preserve optional zero values;
// neither representation replaces stage/bounds/evidence runtime validation.
function goType(node) {
  if (node.$ref) return node.$ref.replace('#/definitions/', '');
  switch (node.type) {
    case 'string': return 'string';
    case 'integer': return 'int64';
    case 'number': return 'float64';
    case 'boolean': return 'bool';
    case 'array': return `[]${goType(node.items)}`;
    case 'object': {
      const required = new Set(node.required ?? []);
      const columns = Object.entries(node.properties).map(([key, value]) => {
        const name = (key[0].toUpperCase() + key.slice(1)).replace(/Id$/, 'ID').replace(/Ms$/, 'MS');
        return [name, `${required.has(key) ? '' : '*'}${goType(value)}`, `\`json:"${key}${required.has(key) ? '' : ',omitempty'}"\``];
      });
      const widths = [0, 1].map(i => Math.max(...columns.map(row => row[i].length)));
      const fields = columns.map(([name, type, tag]) => `\t${name.padEnd(widths[0])} ${type.padEnd(widths[1])} ${tag}`);
      return `struct {\n${fields.join('\n')}\n}`;
    }
    default: throw new Error('Unsupported Go schema shape; update the generator explicitly.');
  }
}

const goGenerated = [
  '// Code generated by npm run generate:contracts; DO NOT EDIT.',
  '// Shape types only. JSON Schema remains authoritative for runtime validation.',
  'package contract',
  `const EventSchemaVersion = ${schema.properties.schemaVersion.const}\nconst MaxEventBytes = ${schema['x-maxUtf8Bytes']}`,
  ...[...Object.entries(schema.definitions), [schema.title, schema]].map(([name, node]) => `type ${name} ${goType(node)}`),
].join('\n\n') + '\n';

if (!process.argv.includes('--check')) await mkdir(new URL('../helper/internal/contract/', import.meta.url), { recursive: true });
const sourceSchema = JSON.parse(await readFile(new URL('../schemas/source-envelope-v1.schema.json', import.meta.url), 'utf8'));
const sourceGenerated = '// Generated by npm run generate:contracts. Do not hand edit.\n\n' +
  `export type SourceEnvelopeV1 = ${typeOf(sourceSchema)};\n` +
  "export type SourceMetadata = NonNullable<SourceEnvelopeV1['result']['metadata']>;\n";
for (const [path, content] of [[output, generated], [new URL('../helper/internal/contract/event_v1.go', import.meta.url), goGenerated], [new URL('../src/transport/sourceContracts.ts', import.meta.url), sourceGenerated]]) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8').catch(() => '') !== content) {
      console.error('Core contracts are stale. Run npm run generate:contracts.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(path, content);
  }
}
