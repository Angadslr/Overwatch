// Package spool publishes metadata through an owned broker or durable inbox.
// The qualified platform is local POSIX; same-user processes are not isolated.
package spool

import (
	"bytes"
	"crypto/rand"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"syscall"
	"time"

	"overwatch/helper/internal/input"
)

const MaxFiles = 10000
const MaxBytes int64 = 25 * 1024 * 1024

var opaqueID = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$`)
var uuidID = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$`)
var hashID = regexp.MustCompile(`^[0-9a-f]{64}$`)

type Config struct {
	Version               int             `json:"configVersion"`
	CollectorID           string          `json:"collectorId"`
	EnvironmentID         string          `json:"environmentId"`
	WorkspaceID           string          `json:"workspaceId"`
	WorktreeID            string          `json:"worktreeId,omitempty"`
	SourceRootHash        string          `json:"sourceRootHash"`
	Enabled               bool            `json:"enabled"`
	PrivacyVersion        int             `json:"privacyVersion,omitempty"`
	PolicyID              string          `json:"policyId,omitempty"`
	AllowedPathHashes     []string        `json:"allowedPathHashes,omitempty"`
	RequireCollectorEpoch bool            `json:"requireCollectorEpoch,omitempty"`
	Broker                *BrokerEndpoint `json:"broker,omitempty"`
}
type Envelope struct {
	Version       int          `json:"transportVersion"`
	EventID       string       `json:"eventId"`
	ReceivedAt    string       `json:"receivedAt"`
	CollectorID   string       `json:"collectorId"`
	EnvironmentID string       `json:"environmentId"`
	WorkspaceID   string       `json:"workspaceId"`
	WorktreeID    string       `json:"worktreeId,omitempty"`
	Result        input.Result `json:"result"`
}

func private(info os.FileInfo) bool {
	stat, ok := info.Sys().(*syscall.Stat_t)
	return ok && int(stat.Uid) == os.Getuid() && info.Mode().Perm()&0077 == 0
}
func secureRead(root *os.Root, name string, max int64) ([]byte, error) {
	before, err := root.Lstat(name)
	if err != nil || !before.Mode().IsRegular() || !private(before) {
		return nil, errors.New("unsafe-spool-file")
	}
	f, err := root.OpenFile(name, os.O_RDONLY|syscall.O_NOFOLLOW|syscall.O_NONBLOCK, 0)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil || !os.SameFile(before, info) || info.Size() > max {
		return nil, errors.New("unsafe-spool-file")
	}
	b, err := io.ReadAll(io.LimitReader(f, max+1))
	if err != nil || int64(len(b)) > max {
		return nil, errors.New("spool-file-too-large")
	}
	return b, nil
}

// Build assigns diagnostic identity once, before retries. Metadata identities
// come from T05 and are never regenerated by Publish.
func Build(config Config, result input.Result) (Envelope, error) {
	id := ""
	if result.Metadata != nil {
		id = result.Metadata.EventID
		matched := len(result.Metadata.WorkspaceRootHashes) == 1 && result.Metadata.WorkspaceRootHashes[0] == config.SourceRootHash
		if !matched || result.Metadata.SourceVersion != "3.26.16" || result.Metadata.SourceEvent == "sessionEnd" {
			return Envelope{}, errors.New("unsupported-source-scope")
		}
	} else {
		if result.Counters.Gap == "" {
			return Envelope{}, errors.New("empty-source-result")
		}
		b := make([]byte, 16)
		if _, err := io.ReadFull(rand.Reader, b); err != nil {
			return Envelope{}, err
		}
		b[6] = (b[6] & 15) | 64
		b[8] = (b[8] & 63) | 128
		id = fmt.Sprintf("%x-%x-%x-%x-%x", b[:4], b[4:6], b[6:8], b[8:10], b[10:])
	}
	if config.Version != 1 || !config.Enabled || !opaqueID.MatchString(config.CollectorID) || !opaqueID.MatchString(config.EnvironmentID) || !opaqueID.MatchString(config.WorkspaceID) || (config.WorktreeID != "" && !opaqueID.MatchString(config.WorktreeID)) || !hashID.MatchString(config.SourceRootHash) || !uuidID.MatchString(id) {
		return Envelope{}, errors.New("invalid-publisher-config")
	}
	receivedAt := time.Now().UTC().Format("2006-01-02T15:04:05.000Z")
	if result.Metadata != nil {
		receivedAt = result.Metadata.ReceivedAt
	}
	return Envelope{Version: 1, EventID: id, ReceivedAt: receivedAt, CollectorID: config.CollectorID, EnvironmentID: config.EnvironmentID, WorkspaceID: config.WorkspaceID, WorktreeID: config.WorktreeID, Result: result}, nil
}

// PublishResult reads extension-owned configuration, builds one immutable
// envelope, and retries publication with the same identity and encoded bytes.
func PublishResult(path string, result input.Result) error {
	return PublishResultForCollector(path, result, "")
}
func PublishResultForCollector(path string, result input.Result, expected string) error {
	canonical, err := filepath.EvalSymlinks(path)
	if err != nil || !filepath.IsAbs(path) || canonical != path {
		return errors.New("unsafe-spool-root")
	}
	info, err := os.Lstat(path)
	if err != nil || !info.IsDir() || !private(info) {
		return errors.New("unsafe-spool-root")
	}
	root, err := os.OpenRoot(path)
	if err != nil {
		return err
	}
	defer root.Close()
	opened, err := root.Stat(".")
	if err != nil || !os.SameFile(info, opened) {
		return errors.New("spool-root-changed")
	}
	configBytes, err := secureRead(root, "publisher.json", 4096)
	if err != nil {
		return err
	}
	var config Config
	d := json.NewDecoder(bytes.NewReader(configBytes))
	d.DisallowUnknownFields()
	if d.Decode(&config) != nil {
		return errors.New("invalid-publisher-config")
	}
	var extra any
	if d.Decode(&extra) != io.EOF {
		return errors.New("invalid-publisher-config")
	}
	check := expected == "" && result.Metadata == nil && result.Counters.Gap == "self-check" && uuidID.MatchString(result.Counters.CheckID)
	if (expected != "" && expected != config.CollectorID) || (config.RequireCollectorEpoch && expected == "" && !check) {
		return errors.New("stale-collector-epoch")
	}
	result = enforcePublicationPolicy(config, result)
	envelope, err := Build(config, result)
	if err != nil {
		return err
	}
	encoded, err := json.Marshal(envelope)
	if err != nil || len(encoded) > input.MaxProjectionBytes {
		return errors.New("projection-too-large")
	}
	if config.RequireCollectorEpoch && tryBroker(config.Broker, envelope, encoded) {
		return nil
	}
	inboxName := "inbox"
	if config.RequireCollectorEpoch {
		inboxName = filepath.Join("inbox", config.CollectorID)
	}
	info, err = root.Lstat(inboxName)
	if err != nil || !info.IsDir() || !private(info) {
		return errors.New("unsafe-spool-inbox")
	}
	inbox, err := root.OpenRoot(inboxName)
	if err != nil {
		return err
	}
	defer inbox.Close()
	opened, err = inbox.Stat(".")
	if err != nil || !os.SameFile(info, opened) {
		return errors.New("spool-inbox-changed")
	}
	for attempt := 0; attempt < 2; attempt++ {
		if err = Publish(inbox, envelope.EventID, encoded); err == nil {
			return nil
		}
	}
	return errors.New("spool-publication-failed")
}

// Publish is idempotent for an identical event. A hard-link publication gives an
// atomic, no-replace ready name; unlike portable Rename it cannot overwrite a
// concurrently published event. Both names are inside the same pinned inbox.
func Publish(inbox *os.Root, eventID string, encoded []byte) error {
	if !uuidID.MatchString(eventID) || len(encoded) > input.MaxProjectionBytes {
		return errors.New("invalid-spool-record")
	}
	ready := eventID + ".json"
	if existing, err := secureRead(inbox, ready, input.MaxProjectionBytes); err == nil {
		if bytes.Equal(existing, encoded) {
			return syncFolder(inbox)
		}
		return errors.New("event-id-conflict")
	}
	directory, err := inbox.Open(".")
	if err != nil {
		return err
	}
	count := 0
	var total int64
	for {
		entries, readErr := directory.Readdir(128)
		for _, entry := range entries {
			count++
			total += entry.Size()
			if count >= MaxFiles || total+int64(len(encoded)) > MaxBytes {
				directory.Close()
				return errors.New("spool-full")
			}
		}
		if readErr == io.EOF {
			break
		}
		if readErr != nil {
			directory.Close()
			return readErr
		}
	}
	directory.Close()
	token := make([]byte, 16)
	if _, err := io.ReadFull(rand.Reader, token); err != nil {
		return err
	}
	token[6] = (token[6] & 15) | 64
	token[8] = (token[8] & 63) | 128
	tmp := fmt.Sprintf("%s.%x-%x-%x-%x-%x.tmp", eventID, token[:4], token[4:6], token[6:8], token[8:10], token[10:])
	f, err := inbox.OpenFile(tmp, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer inbox.Remove(tmp)
	n, writeErr := f.Write(encoded)
	if writeErr == nil && n != len(encoded) {
		writeErr = io.ErrShortWrite
	}
	if writeErr == nil {
		writeErr = f.Sync()
	}
	closeErr := f.Close()
	if writeErr != nil {
		return writeErr
	}
	if closeErr != nil {
		return closeErr
	}
	if err := inbox.Link(tmp, ready); err != nil {
		if existing, readErr := secureRead(inbox, ready, input.MaxProjectionBytes); readErr == nil && bytes.Equal(existing, encoded) {
			return syncFolder(inbox)
		}
		return err
	}
	if err := inbox.Remove(tmp); err != nil {
		return err
	}
	return syncFolder(inbox)
}

func syncFolder(inbox *os.Root) error {
	folder, err := inbox.Open(".")
	if err != nil {
		return err
	}
	defer folder.Close()
	return folder.Sync()
}
